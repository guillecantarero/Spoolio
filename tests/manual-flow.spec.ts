import { test, expect } from '@playwright/test';
import { emptyState } from '../src/domain';

test('recorrido completo local, persistencia y vista móvil', async ({ page }) => {
  await page.addInitScript(state => { if (!localStorage.getItem('spoolio.demo.v1')) localStorage.setItem('spoolio.demo.v1', JSON.stringify(state)); }, { ...emptyState(), visualDemoInitialized: true });
  await page.goto('/');
  await page.getByRole('button', { name: 'Entrar como Mi perfil' }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Escanear', exact: true }).click();
  await page.getByRole('button', { name: 'Añadir manualmente', exact: false }).click();
  await page.getByRole('button', { name: 'Crear un filamento nuevo' }).click();
  await page.getByLabel('Marca', { exact: true }).fill('Winle');
  await page.getByLabel('Material', { exact: true }).fill('PLA');
  await page.getByLabel('Nombre en español').fill('Aurora de prueba');
  await page.getByLabel('Distribución del color').selectOption('gradiente');
  await page.getByLabel('Hexadecimal 1', { exact: true }).fill('#E07090');
  await page.getByRole('button', { name: 'Añadir color' }).click();
  await page.getByLabel('Hexadecimal 2', { exact: true }).fill('#5070B0');
  await page.getByLabel('Muestra hecha').check();
  await page.getByRole('button', { name: 'Guardar filamento' }).click();
  await page.getByRole('combobox', { name: 'Ubicación', exact: true }).selectOption('fablab');
  await page.getByRole('combobox', { name: 'Formato', exact: true }).selectOption('refill');
  await page.getByRole('button', { name: 'Guardar bobina' }).click();
  await expect(page.getByRole('button', { name: /Aurora de prueba/ })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Entrar como Juan' }).click();
  await page.getByRole('button', { name: /Aurora de prueba/ }).click();
  await expect(page.getByText('Refill sin montar', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'La tengo yo' }).click();
  await expect(page.getByText('Fablab → Juan')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Ya está contigo' })).toBeDisabled();
  await page.getByRole('button', { name: 'Mis bobinas', exact: false }).click();
  await expect(page.getByRole('button', { name: /Aurora de prueba/ })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/spoolio-mobile.png', fullPage: true });
  await page.getByRole('button', { name: /Aurora de prueba/ }).click();
  await page.getByRole('button', { name: 'Retirar bobina', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar retirada' }).click();
  await expect(page.getByRole('button', { name: /Aurora de prueba/ })).toHaveCount(0);
  await page.getByRole('button', { name: 'Catálogo', exact: false }).click();
  await expect(page.getByRole('heading', { name: 'Aurora de prueba' })).toBeVisible();
  await expect(page.getByLabel('Muestra hecha')).toBeChecked();
  await expect(page.getByText('0 unidades activas')).toBeVisible();
  await page.getByRole('button', { name: 'Configuración', exact: false }).click();
  await page.getByRole('button', { name: /Aurora de prueba/ }).click();
  await expect(page.getByText('Fablab → Juan')).toBeVisible();
  await expect(page.getByText('Retirada: agotada', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/spoolio-desktop.png', fullPage: true });
});
