import { test, expect } from '@playwright/test';

test('ocho variantes, vistas, edición, temas y limpieza de ejemplos', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Entrar como Mi perfil' }).click();
  await expect(page.locator('.inventory-items .spool-card')).toHaveCount(30);
  await page.getByRole('button', { name: 'Mis bobinas', exact: true }).click();
  await expect(page.locator('.inventory-items .spool-card')).toHaveCount(10);
  const first = page.locator('.inventory-items .spool-card').first();
  const third = page.locator('.inventory-items .spool-card').nth(2);
  const fourth = page.locator('.inventory-items .spool-card').nth(3);
  expect((await first.boundingBox())!.y).toBe((await third.boundingBox())!.y);
  expect((await fourth.boundingBox())!.y).toBeGreaterThan((await first.boundingBox())!.y);
  const ids = await page.locator('.inventory-items svg [id]').evaluateAll(nodes => nodes.map(n => n.id));
  expect(new Set(ids).size).toBe(ids.length);
  await expect(page.locator('.inventory-items [data-part="damero"]')).toHaveCount(4);
  await page.screenshot({ path: 'test-results/spools-grid-dark.png', fullPage: true });
  await page.getByRole('button', { name: 'Vista lista', exact: true }).click();
  await expect(page.locator('.inventory-list')).toBeVisible();
  await page.screenshot({ path: 'test-results/spools-list-dark.png', fullPage: true });
  await page.getByRole('button', { name: /Naranja translúcido.*Montada/ }).click();
  await expect(page.getByText('Translúcido', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Editar / cambiar ubicación' }).click();
  await page.getByRole('combobox', { name: 'Formato', exact: true }).selectOption('refill');
  await expect(page.locator('dialog [data-part="lateral-delantero"]')).toHaveCount(0);
  await page.getByRole('button', { name: 'Guardar bobina' }).click();
  await expect(page.locator('.detail [data-part="lateral-delantero"]')).toHaveCount(0);
  await page.getByRole('button', { name: 'Catálogo', exact: true }).click();
  await page.locator('.catalog-card').filter({ has: page.getByRole('heading', { name: 'Naranja', exact: true }) }).getByRole('button', { name: 'Editar', exact: true }).click();
  await page.getByLabel('Filamento translúcido', { exact: true }).check();
  await expect(page.locator('dialog [data-part="damero"]')).toHaveCount(2);
  await page.getByLabel('Hexadecimal 1', { exact: true }).fill('#ABCDEF');
  await page.getByRole('button', { name: 'Guardar filamento' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Entrar como Mi perfil' }).click();
  await expect(page.locator('.inventory-list')).toBeVisible();
  const data = await page.evaluate(() => JSON.parse(localStorage.getItem('spoolio.demo.v1')!));
  expect(data.filaments.find((f: { id: string }) => f.id === 'visual-orange')).toMatchObject({ translucent: true, colors: [{ hex: '#ABCDEF', name: '' }] });
  await page.getByRole('button', { name: 'Configuración', exact: true }).click();
  await page.getByRole('button', { name: 'Cambiar a modo claro' }).click();
  await page.getByRole('button', { name: 'Mis bobinas', exact: true }).click();
  await page.getByRole('button', { name: 'Vista cuadrícula', exact: true }).click();
  await page.screenshot({ path: 'test-results/spools-grid-light.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/spools-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 320, height: 720 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Configuración', exact: true }).click();
  await page.getByRole('combobox', { name: 'Idioma de los nombres' }).selectOption('en');
  await page.getByRole('button', { name: 'Mis bobinas', exact: true }).click();
  await page.getByRole('textbox', { name: 'Buscar', exact: true }).fill('blanco jade');
  await expect(page.locator('.spool-card')).toHaveCount(1);
  await expect(page.getByRole('heading', { name: 'Jade White', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Buscar', exact: true }).fill('jade white');
  await expect(page.locator('.spool-card')).toHaveCount(1);
  await page.reload();
  await page.getByRole('button', { name: 'Entrar como Mi perfil' }).click();
  await page.getByRole('button', { name: 'Configuración', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Idioma de los nombres' })).toHaveValue('en');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Eliminar ejemplos visuales', exact: true }).click();
  await page.getByRole('button', { name: 'Inventario', exact: true }).click();
  await expect(page.locator('.spool-card')).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: 'Entrar como Mi perfil' }).click();
  await expect(page.locator('.spool-card')).toHaveCount(0);
});
