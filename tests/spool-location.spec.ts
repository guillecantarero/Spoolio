import { test, expect } from '@playwright/test';

test('ubicación con botones, pulsación larga y gesto cancelado', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Entrar como Juan' }).click();
  await page.locator('.spool-card').first().click();
  const trigger = page.locator('.location-action');
  const options = page.getByRole('group', { name: 'Elegir ubicación' });
  await trigger.click();
  await expect(options.getByRole('button')).toHaveCount(4);
  await options.getByRole('button', { name: 'Fablab', exact: true }).click();
  await expect(trigger).toHaveAccessibleName('Cambiar ubicación: Fablab');
  await expect(options).toHaveCount(0);
  const transfers = await page.locator('.timeline li').count();
  await trigger.click();
  await options.getByRole('button', { name: 'Fablab', exact: true }).click();
  await expect(page.locator('.timeline li')).toHaveCount(transfers);
  await trigger.scrollIntoViewIfNeeded();
  const box = (await trigger.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.waitForTimeout(750);
  await page.mouse.up();
  await expect(trigger).toHaveAccessibleName('Cambiar ubicación: Juan');
  await expect(options).toHaveCount(0);
  await expect(page.getByText('Fablab → Juan', { exact: true })).toBeVisible();
  await trigger.click();
  await options.getByRole('button', { name: 'Óscar', exact: true }).click();
  await trigger.dispatchEvent('pointerdown', { button: 0, isPrimary: true, clientX: 20, clientY: 20 });
  await trigger.dispatchEvent('pointercancel');
  await page.waitForTimeout(750);
  await expect(trigger).toHaveAccessibleName('Cambiar ubicación: Óscar');
  await trigger.dispatchEvent('pointerdown', { button: 0, isPrimary: true, clientX: 20, clientY: 20 });
  await trigger.dispatchEvent('pointermove', { clientX: 40, clientY: 40 });
  await page.waitForTimeout(750);
  await trigger.dispatchEvent('pointerup');
  await expect(trigger).toHaveAccessibleName('Cambiar ubicación: Óscar');
  await trigger.focus();
  await page.keyboard.press('Enter');
  await expect(options).toBeVisible();
  await page.screenshot({ path: 'test-results/location-options.png', fullPage: true });
  await page.keyboard.press('Escape');
  await expect(options).toHaveCount(0);
  const unitId = await page.evaluate(() => JSON.parse(localStorage.getItem('spoolio.demo.v1')!).events.at(-1).spoolId as string);
  await page.reload();
  await page.getByRole('button', { name: 'Entrar como Juan' }).click();
  const storedLocation = await page.evaluate(id => JSON.parse(localStorage.getItem('spoolio.demo.v1')!).spools.find((s: { id: string }) => s.id === id).locationId, unitId);
  expect(storedLocation).toBe('oscar');
});

 test('pulsación táctil abre ubicaciones y guarda sin aviso', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:' + (process.env.SPOOLIO_TEST_PORT ?? '5173'));
  await page.getByRole('button', { name: 'Entrar como Juan' }).tap();
  await page.locator('.spool-card').first().tap();
  const trigger = page.locator('.location-action');
  await trigger.tap();
  const options = page.getByRole('group', { name: 'Elegir ubicación' });
  await expect(options.getByRole('button')).toHaveCount(4);
  await options.getByRole('button', { name: 'Fablab', exact: true }).tap();
  await expect(trigger).toHaveAccessibleName('Cambiar ubicación: Fablab');
  await expect(page.getByRole('status')).toHaveCount(0);
  await trigger.tap();
  await expect(options).toBeVisible();
  await options.getByRole('button', { name: 'Juan', exact: true }).tap();
  await expect(trigger).toHaveAccessibleName('Cambiar ubicación: Juan');
  await context.close();
});
